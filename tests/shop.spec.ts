test('owner adds a staff account and staff can only access order management', async ({ page }) => {
  const credentials = { email: 'staff-browser@fillico.test', password: randomBytes(20).toString('base64url') };
  await login(page);
  await page.getByRole('button', { name: 'Nhân viên', exact: true }).click();
  await page.getByRole('button', { name: 'Thêm nhân viên', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Họ và tên', { exact: true }).fill('Nhân viên kiểm thử');
  await dialog.getByLabel('Email đăng nhập', { exact: true }).fill(credentials.email);
  await dialog.locator('input[autocomplete="new-password"]').fill(credentials.password);
  await dialog.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await login(page, credentials);
  await expect(page.getByRole('heading', { level: 1, name: 'Đơn hàng', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Sản phẩm & kho', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Banner trang chủ', exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/admin/products')).status()).toBe(403);
  expect((await page.request.get('/api/admin/settings')).status()).toBe(403);
  expect((await page.request.get('/api/admin/orders')).status()).toBe(200);
  const updatedPassword = randomBytes(20).toString('base64url');
  await page.getByRole('button', { name: 'Đổi mật khẩu', exact: true }).click();
  const passwordDialog = page.getByRole('dialog');
  await passwordDialog.getByLabel('Mật khẩu hiện tại', { exact: true }).fill(credentials.password);
  await passwordDialog.locator('input[autocomplete="new-password"]').nth(0).fill(updatedPassword);
  await passwordDialog.getByLabel('Nhập lại mật khẩu mới', { exact: true }).fill(updatedPassword);
  await passwordDialog.getByRole('button', { name: 'Đổi mật khẩu', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Đăng nhập', exact: true })).toBeVisible();
  expect((await page.request.get('/api/auth/me')).status()).toBe(401);
  await login(page, { ...credentials, password: updatedPassword });
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await login(page);
  await page.getByRole('button', { name: 'Nhân viên', exact: true }).click();
  await page.getByRole('row').filter({ hasText: credentials.email }).getByRole('button', { name: 'Thu hồi quyền', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Thu hồi quyền', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: credentials.email })).toHaveCount(0);
  expect((await page.request.post('/api/auth/login', { data: { ...credentials, password: updatedPassword } })).status()).toBe(401);
});

