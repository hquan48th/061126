import { test, expect, type Page } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
import type { Product, Settings, Order } from '../shared/types';

function ownerCredentials() {
  const text = readFileSync(join(process.env.FILLICO_E2E_DATA_DIR!, 'admin-credentials.txt'), 'utf8');
  const email = text.match(/^Email: (.+)$/m)?.[1];
  const password = text.match(/^Password: (.+)$/m)?.[1];
  if (!email || !password) throw new Error('The isolated test owner account was not initialized.');
  return { email, password };
}

async function login(page: Page, credentials = ownerCredentials()) {
  await page.goto('/admin');
  await page.getByLabel('Địa chỉ email').fill(credentials.email);
  await page.locator('input[autocomplete="current-password"]').fill(credentials.password);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Đăng xuất', exact: true })).toBeVisible();
}

async function getStore(page: Page): Promise<{ products: Product[]; settings: Settings }> {
  const response = await page.request.get('/api/store');
  expect(response.ok()).toBeTruthy();
  return response.json();
}

async function expectNoOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
}

test('homepage images, catalog search, categories, price sorting and saved favorites', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const { products, settings } = await getStore(page);
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(settings.heroTitle);
  await expect(page.locator('.hero-visual img')).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await expect.poll(() => page.locator('.hero-visual img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBeTruthy();
  await page.locator('.category-grid').scrollIntoViewIfNeeded();
  await expect.poll(() => page.locator('.category-grid img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBeTruthy();
  await page.evaluate(() => window.scrollTo(0, 0));
  await expectNoOverflow(page);
  await page.screenshot({ path: info.outputPath('desktop-home.png'), fullPage: true });
  await page.getByRole('link', { name: 'Khám phá sản phẩm', exact: true }).click();
  await expect(page.locator('.catalog-results .product-card')).toHaveCount(products.length);
  await page.getByRole('textbox', { name: 'Tìm trong danh sách sản phẩm' }).fill('ban chai');
  await expect(page.locator('.catalog-results .product-card')).toHaveCount(1);
  await expect(page.locator('.product-name')).toHaveText('Bàn chải tre tự nhiên');
  await page.getByRole('button', { name: 'Yêu thích Bàn chải tre tự nhiên', exact: true }).click();
  await page.goto('/san-pham?filter=favorites');
  await expect(page.locator('.catalog-results .product-card')).toHaveCount(1);
  await page.reload();
  await expect(page.locator('.product-name')).toHaveText('Bàn chải tre tự nhiên');
  await page.goto('/san-pham');
  await page.getByRole('button', { name: /^Khăn & vải/ }).click();
  await expect(page.locator('.catalog-results .product-card')).toHaveCount(products.filter(p => p.category === 'Khăn & vải').length);
  await page.getByLabel('Chỉ sản phẩm còn hàng').check();
  await expect(page.locator('.catalog-results .product-card')).toHaveCount(products.filter(p => p.category === 'Khăn & vải' && p.variants.some(v => v.stock > 0)).length);
  await page.goto('/san-pham');
  await page.getByLabel('Sắp xếp sản phẩm').selectOption('price-asc');
  const prices = await page.locator('.product-info .price-row strong').allTextContents();
  const numbers = prices.map(price => Number(price.replace(/\D/g, '')));
  expect(numbers).toEqual([...numbers].sort((a, b) => a - b));
  await page.getByRole('textbox', { name: 'Tìm trong danh sách sản phẩm' }).fill('unfindable-website-check');
  await expect(page.getByRole('heading', { name: 'Chưa tìm thấy sản phẩm' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('variant cart persists, COD checkout tracks privately, and admin cancellation restores inventory once', async ({ page }, info) => {
  const before = await getStore(page);
  const product = before.products.find(p => p.slug === 'ban-chai-tre')!;
  const variant = product.variants[1];
  await page.goto('/san-pham/' + product.slug);
  await page.getByRole('button', { name: variant.name, exact: true }).click();
  await page.getByRole('button', { name: 'Tăng số lượng', exact: true }).click();
  await page.getByRole('button', { name: 'Thêm vào giỏ', exact: true }).click();
  await page.getByRole('button', { name: 'Mở giỏ hàng', exact: true }).click();
  const cart = page.getByRole('dialog');
  await expect(cart.getByText(variant.name, { exact: true })).toBeVisible();
  await expect(cart.locator('.quantity span')).toHaveText('2');
  await cart.getByRole('button', { name: 'Đóng', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Mở giỏ hàng', exact: true }).click();
  await expect(page.getByRole('dialog').locator('.quantity span')).toHaveText('2');
  await page.getByRole('link', { name: 'Tiến hành đặt hàng' }).click();
  await expect(page.getByRole('heading', { name: 'Hoàn tất đơn hàng.' })).toBeVisible();
  await page.getByLabel(/Họ và tên/).fill('Khách kiểm thử đơn hàng');
  await page.getByLabel(/Số điện thoại/).fill('0901234567');
  await page.getByLabel(/Địa chỉ nhận hàng/).fill('123 Nguyễn Trãi, phường Bến Thành, Thành phố Hồ Chí Minh');
  await page.getByLabel(/Tôi đồng ý/).check();
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/orders') && response.request().method() === 'POST');
  await page.getByRole('button', { name: /^Đặt hàng ·/ }).click();
  const response = await responsePromise;
  expect(response.status()).toBe(201);
  const placed = await response.json() as { order: Order; trackingToken: string };
  expect(placed.order.total).toBe(variant.price * 2 + before.settings.shippingFee);
  await expect(page.getByText('Đặt hàng thành công!', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: placed.order.code, exact: true })).toBeVisible();
  const trackingUrl = page.url();
  const after = await getStore(page);
  expect(after.products.find(p => p.id === product.id)!.variants.find(v => v.id === variant.id)!.stock).toBe(variant.stock - 2);
  expect((await page.request.get('/api/orders/' + placed.order.code + '?token=wrong')).status()).toBe(404);
  await login(page);
  await page.screenshot({ path: info.outputPath('seller-dashboard.png'), fullPage: true });
  await page.getByRole('button', { name: /^Đơn hàng/ }).first().click();
  await page.getByRole('button', { name: 'Xem đơn ' + placed.order.code, exact: true }).click();
  await page.getByRole('button', { name: 'In / chỉnh sửa phiếu', exact: true }).click();
  const receipt = page.getByRole('dialog');
  const editor = receipt.getByLabel('Nội dung phiếu');
  await expect(editor).toHaveValue(/PHIẾU BÁN HÀNG/);
  await receipt.screenshot({ path: info.outputPath('receipt-editor.png') });
  const original = await editor.inputValue();
  await editor.fill(original + '\nGhi chú kiểm thử riêng cho đơn này');
  await receipt.getByRole('button', { name: 'Lưu phiếu', exact: true }).click();
  await expect(receipt.getByRole('status')).toContainText('Đã lưu nội dung');
  await receipt.getByRole('button', { name: 'Quay lại đơn hàng' }).click();
  await page.getByRole('button', { name: 'In / chỉnh sửa phiếu', exact: true }).click();
  await expect(page.getByLabel('Nội dung phiếu')).toHaveValue(/Ghi chú kiểm thử riêng/);
  const printWindow = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'Lưu và in', exact: true }).click();
  const printed = await printWindow;
  await expect(printed.locator('pre')).toContainText('Ghi chú kiểm thử riêng');
  await printed.close();
  await page.getByRole('button', { name: 'Quay lại đơn hàng' }).click();
  await page.getByRole('dialog').getByRole('combobox', { name: 'Trạng thái đơn hàng', exact: true }).selectOption('cancelled');
  await page.getByRole('button', { name: 'Cập nhật đơn hàng', exact: true }).click();
  await expect(page.getByRole('dialog').getByText('Đã hủy', { exact: true }).first()).toBeVisible();
  await expect.poll(async () => (await getStore(page)).products.find(p => p.id === product.id)!.variants.find(v => v.id === variant.id)!.stock).toBe(variant.stock);
  const unchanged = await page.request.patch('/api/admin/orders/' + placed.order.id, { data: { status: 'cancelled' } });
  expect(unchanged.ok()).toBeTruthy();
  expect((await getStore(page)).products.find(p => p.id === product.id)!.variants.find(v => v.id === variant.id)!.stock).toBe(variant.stock);
  await page.goto(trackingUrl);
  await expect(page.locator('.order-status')).toHaveText('Đã hủy');
});

