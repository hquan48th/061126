SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS schema_migrations (version INT PRIMARY KEY, applied_at VARCHAR(32) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS products (
 seq BIGINT UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
 id VARCHAR(100) COLLATE utf8mb4_bin PRIMARY KEY,
 slug VARCHAR(160) COLLATE utf8mb4_bin NOT NULL UNIQUE,
 data LONGTEXT NOT NULL CHECK(JSON_VALID(data))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS variants (
 seq BIGINT UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
 id VARCHAR(100) COLLATE utf8mb4_bin PRIMARY KEY,
 product_id VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
 data LONGTEXT NOT NULL CHECK(JSON_VALID(data)),
 INDEX variants_product(product_id), FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS settings (id INT PRIMARY KEY, data LONGTEXT NOT NULL CHECK(JSON_VALID(data)), CHECK(id=1)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS orders (
 seq BIGINT UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
 id VARCHAR(100) COLLATE utf8mb4_bin PRIMARY KEY,
 code VARCHAR(100) COLLATE utf8mb4_bin NOT NULL UNIQUE,
 token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 data LONGTEXT NOT NULL CHECK(JSON_VALID(data))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS order_receipts (
 order_id VARCHAR(100) COLLATE utf8mb4_bin PRIMARY KEY,
 content MEDIUMTEXT NOT NULL, updated_at VARCHAR(32) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS idempotency (
 `key` VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 request_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 response LONGTEXT NOT NULL CHECK(JSON_VALID(response))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS users (
 seq BIGINT UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
 id VARCHAR(100) COLLATE utf8mb4_bin PRIMARY KEY,
 email VARCHAR(254) COLLATE utf8mb4_bin NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL, role VARCHAR(10) NOT NULL,
 password_hash VARCHAR(255) NOT NULL, CHECK(role IN ('owner','staff'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 user_id VARCHAR(100) COLLATE utf8mb4_bin NOT NULL, expires BIGINT NOT NULL,
 INDEX sessions_expires(expires), INDEX sessions_user(user_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id VARCHAR(100) COLLATE utf8mb4_bin NULL,
 action VARCHAR(100) NOT NULL, detail LONGTEXT NOT NULL CHECK(JSON_VALID(detail)),
 created_at VARCHAR(32) NOT NULL, INDEX audit_date(created_at), INDEX audit_user(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
-- Persistent across PHP requests/workers. IPs are stored as SHA-256 hashes.
CREATE TABLE IF NOT EXISTS login_attempts (
 ip_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL, until_ms BIGINT NOT NULL, INDEX attempts_until(until_ms)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
